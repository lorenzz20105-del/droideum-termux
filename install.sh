#!/data/data/com.termux/files/usr/bin/bash
# =============================================================================
#  droideum installer — run this INSIDE Termux (not inside proot).
#
#     curl -LO <this repo>/install.sh && bash install.sh
#
#  What it does:
#    1. checks that you really are on Termux/Android
#    2. installs proot-distro + aarch64 Debian container
#    3. copies the droideum engine into the container
#    4. creates a Termux command `droideum` that re-execs into the container
#    5. binds ~/droideum (Termux side) to /root/.droideum so your VM, ISO and
#       apps survive container rebuilds
#
#  Uninstall:  bash install.sh --uninstall
# =============================================================================
set -euo pipefail

DISTRO="debian"
SRC_DIR="$(cd "$(dirname "${BASH_SOURCE[0]:-$0}")" && pwd)"
TERMUX_HOME="${HOME:-/data/data/com.termux/files/home}"
DATA_DIR="$TERMUX_HOME/droideum"          # host-side, survives everything
WRAPPER="$PREFIX/bin/droideum"

c_r=$'\033[0m'; c_b=$'\033[1m'; c_g=$'\033[32m'; c_y=$'\033[33m'; c_e=$'\033[31m'; c_c=$'\033[36m'; c_d=$'\033[2m'
info() { printf '%s==>%s %s\n' "$c_c" "$c_r" "$*"; }
ok()   { printf '%s  ok%s %s\n' "$c_g" "$c_r" "$*"; }
warn() { printf '%s warn%s %s\n' "$c_y" "$c_r" "$*" >&2; }
die()  { printf '%serr %s %s\n' "$c_e" "$c_r" "$*" >&2; exit 1; }
step() { printf '\n%s%s%s\n' "$c_b" "$*" "$c_r"; }

# --- 0. sanity ---------------------------------------------------------------
[ -n "${PREFIX:-}" ] && [ -d "$PREFIX" ] || \
  die "This must run inside Termux (PREFIX is not set). Download Termux from F-Droid, then re-run."
case "${PREFIX:-}" in
  *com.termux*) : ;;
  *) warn "PREFIX=$PREFIX does not look like Termux; continuing anyway" ;;
esac
command -v proot-distro >/dev/null 2>&1 ||   warn "proot-distro is not installed yet — this installer will add it"

if [ "${1:-}" = "--uninstall" ]; then
  step "Uninstalling droideum"
  rm -f "$WRAPPER"
  ok "removed $WRAPPER"
  if [ -d "$DATA_DIR" ]; then
    warn "your data is kept at $DATA_DIR (VM disk, ISO, config)"
    say_hint="  delete it with:  rm -rf $DATA_DIR"
    printf '%s\n' "$say_hint"
  fi
  exit 0
fi

step "1/6  Termux packages"
export DEBIAN_FRONTEND=noninteractive
pkg update -y >/dev/null 2>&1 || warn "pkg update had warnings (continuing)"
for p in proot-distro curl coreutils tar; do
  if pkg list-installed 2>/dev/null | grep -q "^$p/"; then ok "$p already installed"
  else pkg install -y "$p" >/dev/null 2>&1 && ok "$p installed" || die "could not install $p"; fi
done
command -v proot-distro >/dev/null 2>&1 || die "proot-distro not on PATH after install"

step "2/6  aarch64 Linux container ($DISTRO)"
if [ -d "$PREFIX/var/lib/proot-distro/installed-rootfs/$DISTRO" ]; then
  ok "$DISTRO rootfs present"
else
  info "installing $DISTRO (~200 MB download) ..."
  proot-distro install "$DISTRO" || die "proot-distro install $DISTRO failed"
  ok "$DISTRO installed"
fi
ROOTFS="$PREFIX/var/lib/proot-distro/installed-rootfs/$DISTRO"
[ -d "$ROOTFS" ] || die "cannot find rootfs at $ROOTFS"

step "3/6  installing the engine into the container"
mkdir -p "$ROOTFS/usr/local/bin"
ENGINE_SRC=""
for cand in "$SRC_DIR/bin/droideum" "$SRC_DIR/droideum"; do
  [ -f "$cand" ] && ENGINE_SRC="$cand" && break
done
[ -n "$ENGINE_SRC" ] || die "cannot find bin/droideum next to install.sh"
install -m 0755 "$ENGINE_SRC" "$ROOTFS/usr/local/bin/droideum"
ok "engine installed -> /usr/local/bin/droideum (inside $DISTRO)"

AGENTD_SRC="$SRC_DIR/bin/droideum-agentd"
if [ -f "$AGENTD_SRC" ]; then
  install -m 0755 "$AGENTD_SRC" "$ROOTFS/usr/local/bin/droideum-agentd"
  ok "agent control plane -> /usr/local/bin/droideum-agentd (MCP server, stdlib only)"
else
  warn "bin/droideum-agentd missing — agent mode will be unavailable"
fi

step "4/6  VM data directory (survives container rebuilds)"
mkdir -p "$DATA_DIR/cache" "$DATA_DIR/logs"
ok "data dir: $DATA_DIR"

step "5/6  Termux command wrapper"
cat > "$WRAPPER" <<EOF
#!/data/data/com.termux/files/usr/bin/bash
# generated by droideum install.sh — re-execs the engine inside proot-distro
set -euo pipefail
# proot login sanitises the environment, so pass DROIDEUM_HOME explicitly.
# Other overrides (RAM_MB, VNC_DISPLAY, ...) belong in ~/droideum/droideum.conf
exec proot-distro login $DISTRO \\
  --bind "$DATA_DIR:/root/.droideum" \\
  -- env DROIDEUM_HOME=/root/.droideum /usr/local/bin/droideum "\$@"
EOF
chmod +x "$WRAPPER"
ok "wrapper: $WRAPPER"

# convenience extras (optional, never fatal)
if ! command -v termux-wake-lock >/dev/null 2>&1; then
  warn "termux-api not installed — 'pkg install termux-api' lets you keep the CPU awake"
fi

step "6/6  Screen, input and storage tips"
cat <<'EOF'
  Install a VNC viewer from the Play Store / F-Droid so you can SEE Android:
      bVNC, MultiVNC, AVNC or RealVNC Viewer
  Then connect to:   127.0.0.1:5900

  For a real desktop feel instead of VNC:
      pkg install x11-repo && pkg install termux-x11-nightly
      (then set DISPLAY_BACKEND=gtk in ~/.droideum/droideum.conf)

  Keep Termux alive during the long install (it takes a while):
      termux-wake-lock
      Android Settings -> Apps -> Termux -> Battery -> Unrestricted
EOF

printf '\n%sdroideum is installed.%s\n\n' "$c_b" "$c_r"
cat <<'EOF'
Next steps (type these in Termux):

  termux-wake-lock           # optional but strongly recommended
  droideum doctor            # sanity check
  droideum setup             # engine + ~965 MB Android image + 16 GB disk
  droideum install           # boot the installer, then pick "Install to harddisk"
  droideum start             # boot your Android VM
  droideum apk install app.apk
  droideum apk run com.example.app

For AI agents (no VNC, machine-readable):
  droideum up                              # headless boot, blocks until adb answers
  droideum agent serve --autostart         # MCP server on stdio (25 tools)
  droideum agent config claude             # paste-ready MCP client config
  droideum agent tool                      # what the agent can do

Full guide: README.md   ·   Route/perf reality check: docs/ROUTES.md
EOF
